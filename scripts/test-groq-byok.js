'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const get=p=>fs.readFileSync(p,'utf8');
const gate=get('CaptionIA/js/groq_access.js'),transcript=get('CaptionIA/js/cloud_audio_panel.js'),narrative=get('CaptionIA/js/narrative-beta.js');
const manifest=get('CaptionIA/CSXS/manifest.xml');
assert.match(manifest,/ExtensionBundleVersion="3\.5\.1"/);
assert(gate.includes("'/groq/status'"),'Plugin must query account-owned credential status');
assert(gate.includes('Abrir minha conta'),'Web account setup button');
assert(!gate.includes('fsSecureKeyStore'),'Groq gate must NOT use local key storage');
assert(!gate.includes("api.groq.com"),'Groq secret must not be used on client');
assert(transcript.includes('/api/v1/groq/transcription'),'Transcription must use server gateway');
assert(narrative.includes('/api/v1/groq/narrative/analyze'),'Narrative must use server gateway');
assert(!transcript.includes('api.groq.com'),'No direct transcription to Groq');
assert(!narrative.includes('api.groq.com'),'No direct narrative to Groq');
assert(!transcript.includes('ownKey()'),'No local Groq Keychain retrieval');
console.log('PASS BYOK account integration, no client key and native access gate');
