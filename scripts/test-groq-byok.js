'use strict';
const fs=require('fs'),assert=require('assert'),path=require('path');
const root=path.resolve(__dirname,'..');
const panel=fs.readFileSync(path.join(root,'CaptionIA/js/cloud_audio_panel.js'),'utf8');
const store=fs.readFileSync(path.join(root,'CaptionIA/js/secure_storage.js'),'utf8');
const main=fs.readFileSync(path.join(root,'CaptionIA/js/main.js'),'utf8');
const manifest=fs.readFileSync(path.join(root,'CaptionIA/CSXS/manifest.xml'),'utf8');
assert(panel.includes("modeOption('cloud','Groq da nuvem (padrão)')"),'Default cloud');
assert(panel.includes("modeOption('personal','Minha chave Groq')"),'BYOK switch');
assert(panel.includes("field('personal_groq_key',personalKey)"),'transient BYOK upload');
assert(panel.includes("keyInput.type='password'"),'hidden user input');
assert(panel.includes("w.fsSecureKeyStore.set(key)"),'secure user store');
assert(!panel.includes("field('consent'"),'No consent field');
assert(!panel.includes("consent.checked"),'No user checkbox');
assert(!panel.includes('Limite diário de transcrições atingido'),'No daily cap copy');
assert(panel.includes('o áudio é enviado via Caption IA à Groq'),'Privacy info remains');
assert(store.includes('windows-dpapi'),'Windows credentials protected');
assert(main.includes("CURRENT_VERSION='3.4.4'"),'version main 3.4.4');
assert(manifest.includes('ExtensionBundleVersion="3.4.4"'),'version manifest 3.4.4');
console.log('Groq Cloud/BYOK/Privacy plugin smoke: PASS');
