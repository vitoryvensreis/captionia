'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const html=fs.readFileSync('CaptionIA/index.html','utf8');
const cloud=fs.readFileSync('CaptionIA/js/cloud_audio_panel.js','utf8');
const core=fs.readFileSync('CaptionIA/js/cloud_core.js','utf8');
const manifest=fs.readFileSync('CaptionIA/CSXS/manifest.xml','utf8');
const release=fs.readFileSync('CaptionIA/js/main.js','utf8');
const auth=fs.readFileSync('CaptionIA/js/auth.js','utf8');
const updater=fs.readFileSync('CaptionIA/js/updater.js','utf8');
const installer=fs.readFileSync('INSTALAR_CAPTION_IA.bat','utf8');
const ps=fs.readFileSync('INSTALAR_CAPTION_IA.ps1','utf8');
assert.match(manifest,/ExtensionBundleVersion="3\.4\.4"/);
assert.match(release,/CURRENT_VERSION='3\.4\.4'/);
assert.match(auth,/VERSION='3\.4\.4'/);
assert.match(updater,/CURRENT_VERSION='3\.4\.4'/);
assert(!html.includes('id="cia-cloud-captions-script"'),'Preview Cloud de homologação exposta ao cliente');
assert(!html.includes('<script src="js/sfx_track_diagnostics.js"></script>'),'Diagnóstico de trilhas exposto ao cliente');
assert(html.includes('src="js/cloud_audio_panel.js"'));
assert(cloud.includes("event.stopImmediatePropagation()"),'Botões locais legados não interceptados');
assert(cloud.includes("w.fsAutoEditTranscrever=function(done)"),'Etapa transcrever do AutoEdit não usa o novo fluxo');
assert(cloud.includes("fsExportAudioTrilha("),'Áudio da timeline não é exportado pelo novo fluxo');
assert(cloud.includes("CaptionIACloudCore.planCaptions"),'Planejamento de legendas não usa API');
assert(cloud.includes('w.CaptionIALicense.isAuthorized()'));
assert(cloud.includes("?'personal':'cloud'"),'Nuvem precisa ser o modo padrão');
assert(cloud.includes("'api.groq.com'"),'Modo de chave Groq pessoal não aponta para a Groq');
assert(cloud.includes('w.fsSecureKeyStore.set(key)'),'Chave pessoal precisa usar armazenamento seguro');
assert(cloud.includes('Minha chave Groq'),'Opção de chave Groq pessoal não está na interface');
assert(!cloud.includes("localStorage.setItem('framespeed_groq_key'"),'Chave não deve ficar em texto puro');
assert(!/consent\.checked|Autorizo o envio|Marque a autorização/i.test(cloud),'Transcrição ainda exige checkbox');
assert(core.includes('caption.escotilhaprodutora.com'));
assert(!core.includes("DOMContentLoaded',attachCloudCaptionPanel"),'Não injetar painéis beta');
assert(installer.includes('INSTALAR_CAPTION_IA.ps1'),'Instalador BAT não chama o mecanismo seguro');
assert(ps.includes('Move-Item') && ps.includes('BackupDir') && ps.includes('Start-Transcript'),'Instalador sem backup/log/rollback');
assert(!manifest.includes('<Icons>'),'Manifest não pode usar ícones antigos da marca FrameSpeed');
assert(html.includes('src="js/sfx_media_store.js"'),'Media SFX não carregada antes do AutoSFX');
assert(fs.readFileSync('CaptionIA/js/autosfx.js','utf8').includes('CaptionIASfxMedia.prepareMix(g)'),'AutoSFX sem verificação de mídias persistentes');
assert(!fs.existsSync('CaptionIA/icons') && !fs.existsSync('CaptionIA/logo.png'),'Logo VF ainda empacotada');
assert(installer.includes('fs\\cloud_audio_panel.js')===false);
console.log('Release client smoke PASS: 3.4.5, Nuvem padrão + chave Groq pessoal, sem consentimento obrigatório, safe installer');
